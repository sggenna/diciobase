// Regenerates src/lib/heroWords.ts from the dictionaries the app really serves.
// Needs the API running: pnpm --dir server dev, then: node scripts/hero-words.mjs
// Each word must have a definition in its own dictionary or the script stops, so
// a card can never promise an entry that isn't there.
import { writeFileSync } from "node:fs"

const API = process.env.API_URL ?? "http://localhost:3001/api"
const OUT = new URL("../src/lib/heroWords.ts", import.meta.url)
const MAX_DEF = 52

const CARDS = {
  wikcionario: ["saudade", "terra", "casa", "etimologia"],
  "dicionario-aberto": ["lembrança", "carregar", "caixa", "chuva"],
  wordnet: ["nostalgia", "anseio", "palavra", "viagem"],
}
const HEADLINE = ["saudade", "terra", "cafuné", "sertão", "memória"]

async function lookup(word) {
  const res = await fetch(`${API}/words/${encodeURIComponent(word)}`)
  if (!res.ok) throw new Error(`${word}: HTTP ${res.status}`)
  const entry = (await res.json()).entries[0]
  if (!entry) throw new Error(`${word}: no entry`)
  return entry
}

function firstDefinition(entry, dict) {
  if (dict === "wordnet") return entry.senses.find((s) => s.gloss)?.gloss ?? null
  return entry.dictionaries.find((d) => d.slug === dict)?.entries.flatMap((e) => e.senses)[0]?.text ?? null
}

/** The first clause when it fits, otherwise whole words with an ellipsis: the text is never reworded. */
function shorten(text) {
  const t = text.trim().replace(/[.;:,\s]+$/, "")
  if (t.length <= MAX_DEF) return t
  const clause = t.split(/[;,:]/)[0].trim()
  if (clause.length >= 12 && clause.length <= MAX_DEF) return clause
  return `${t.slice(0, MAX_DEF).replace(/\s+\S*$/, "")}…`
}

const cards = {}
for (const [dict, words] of Object.entries(CARDS)) {
  cards[dict] = []
  for (const word of words) {
    const def = firstDefinition(await lookup(word), dict)
    if (!def) throw new Error(`${word}: no definition in ${dict}`)
    cards[dict].push({ word, def: shorten(def) })
  }
}
for (const word of HEADLINE) await lookup(word)

writeFileSync(
  OUT,
  `// Generated by scripts/hero-words.mjs from the API. Don't edit by hand; change the lists there and run it again.
export const HERO_CARDS: Record<string, { word: string; def: string }[]> = ${JSON.stringify(cards, null, 2)}

export const HERO_WORDS = ${JSON.stringify(HEADLINE)}
`,
)
console.log("Wrote src/lib/heroWords.ts")
